        private string[] _bitmap;
        private Color _color;

        public PixelIcon(string icon, Color color, float size = 24)
        {
            _bitmap = Icons.TryGetValue(icon, out var b) ? b : Icons["star"];
            _color = color;
            style.width = style.height = size;
            style.flexShrink = 0;
            pickingMode = PickingMode.Ignore;
            generateVisualContent += Draw;
        }

        public void SetColor(Color color)
        {
            _color = color;
            MarkDirtyRepaint();
        }

        private void Draw(MeshGenerationContext context)
        {
            var p = context.painter2D;
            float cell = Mathf.Min(contentRect.width, contentRect.height) / 8f;
            p.fillColor = _color;
            for (int y = 0; y < 8; y++)
            for (int x = 0; x < 8; x++)
            {
                if (_bitmap[y][x] != '#') continue;
                p.BeginPath();
                p.MoveTo(new Vector2(x * cell, y * cell));
                p.LineTo(new Vector2((x + 1) * cell, y * cell));
                p.LineTo(new Vector2((x + 1) * cell, (y + 1) * cell));
                p.LineTo(new Vector2(x * cell, (y + 1) * cell));
                p.ClosePath();
                p.Fill();
            }
        }
