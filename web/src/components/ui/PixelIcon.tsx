  friends: ["........", ".##..##.", ".##..##.", "........", "###..###", "###..###", "###..###", "........"],
  me: ["..####..", "..####..", "..####..", "...##...", ".######.", "#.####.#", "..#..#..", "..#..#.."],
  shard: ["...#....", "..###...", ".#####..", "#######.", ".#####..", "..###...", "...#....", "........"],
  bolt: ["....##..", "...##...", "..##....", ".######.", "....##..", "...##...", "..##....", ".#......"],
